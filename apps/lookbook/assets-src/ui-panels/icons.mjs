/** Recolourings of `potion-red`: the same flask with another liquid. */
const POTIONS = {
  'potion-blue': {r: 'b', R: 'B', P: 'c'},
  'potion-green': {r: 'G', R: 'D', P: 'w'},
};

/** @returns {{name: string, img: import('../lib/image.mjs').Img}[]} */
export function icons() {
  /** @type {Record<string, string[]>} */
  const all = {...ICONS};
  for (const [name, map] of Object.entries(POTIONS)) {
    all[name] = ICONS['potion-red'].map((row) =>
      [...row].map((ch) => /** @type {Record<string, string>} */ (map)[ch] ?? ch).join(''),
    );
  }
  return Object.entries(all).map(([name, rows]) => {
    if (rows.length !== 12 || rows.some((r) => r.length !== 12)) throw new Error(`icon ${name} is not 12 × 12`);
    return {name: `icon-${name}`, img: fromAscii(rows, PALETTE)};
  });
}
