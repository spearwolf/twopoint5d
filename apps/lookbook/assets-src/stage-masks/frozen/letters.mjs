/**
 * The strokes of one glyph as an SVG path, centred on (0, 0), `h` tall, y down.
 * @param {string} ch @param {number} h
 */
export function glyphPath(ch, h) {
  const glyph = GLYPHS[ch];
  if (!glyph) throw new Error(`glyphPath: no glyph for ${JSON.stringify(ch)}`);
  const s = h / 6;
  const r = (/** @type {number} */ v) => (Math.round(v * 100) / 100).toString();
  return glyph.map((line) => `M${line.map(([x, y]) => `${r((x - 2) * s)} ${r((y - 3) * s)}`).join('L')}`).join('');
}

/** The width of a glyph of height `h`, for spacing. @param {number} h */
export const glyphWidth = (h) => (h / 6) * 4;
